package fr.skyle.scanny.ui.core.code.model

/** A piece of the content of a code: a network, a password, a recipient… */
data class CodeField(
    // Null for the content itself, a text or a link, which needs no name
    val label: CodeFieldLabel?,
    val value: String,
    // How to show the value in the language of the device when it is not a text: a date, a recurrence…
    val display: CodeFieldDisplay? = null,
) {
    // A password is hidden until touched: the screen may be seen by others
    val isSecret: Boolean
        get() = label == CodeFieldLabel.PASSWORD
}

enum class CodeFieldLabel {
    NETWORK,
    SECURITY,
    PASSWORD,
    PASSWORD_IDENTIFIER,
    PUBLIC_KEY,
    EAP_METHOD,
    IDENTITY,
    ANONYMOUS_IDENTITY,
    PHASE2_METHOD,
    RECIPIENT,
    CARBON_COPY,
    BLIND_CARBON_COPY,
    SUBJECT,
    MESSAGE,
    PHONE_NUMBER,
    NAME,
    NICKNAME,
    ORGANIZATION,
    DEPARTMENT,
    JOB_TITLE,
    PHONE,
    MOBILE,
    HOME_PHONE,
    WORK_PHONE,
    FAX,
    EMAIL,
    HOME_EMAIL,
    WORK_EMAIL,
    ADDRESS,
    HOME_ADDRESS,
    WORK_ADDRESS,
    WEBSITE,
    HOME_WEBSITE,
    WORK_WEBSITE,
    BIRTHDAY,
    NOTE,
    PLACE,
    COORDINATES,
    ALTITUDE,
    UNCERTAINTY,
    TITLE,
    START,
    END,
    DESCRIPTION,
    ORGANIZER,
    ATTENDEE,
    RECURRENCE,
    REMINDER,
    STATUS,
    AVAILABILITY,
    CLASSIFICATION,
    PRIORITY,
    CATEGORIES,
    LINK,
    ISSUER,
    ACCOUNT,
    SECRET_KEY,
    OTP_TYPE,
    ALGORITHM,
    DIGITS,
    PERIOD,
    COUNTER,
    AMOUNT,
}